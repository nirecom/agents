# session-sync.ps1 - Sync Claude Code session history across machines
# Usage:
#   .\session-sync.ps1 push    # Commit and push session data
#   .\session-sync.ps1 pull    # Pull latest session data
#   .\session-sync.ps1 status  # Show sync status
#   .\session-sync.ps1 reset   # Force-sync local to remote (for initial setup or recovery)

param(
    [Parameter(Mandatory, Position = 0)]
    [ValidateSet("push", "pull", "status", "reset")]
    [string]$Action,

    [string]$ClaudeDir = (Join-Path $env:USERPROFILE ".claude"),

    [switch]$Quiet
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ProjectsDir = Join-Path $ClaudeDir "projects"
$helperJs = if ($env:AGENTS_CONFIG_DIR) { Join-Path $env:AGENTS_CONFIG_DIR "hooks/lib/workflow-plans-dir.js" } else { $null }
$PlansDir = if ($helperJs -and (Test-Path $helperJs)) {
    & node -e "process.stdout.write(require('$($helperJs -replace '\\','/'  )').getWorkflowPlansDir())" 2>$null
} else { Join-Path $env:USERPROFILE ".workflow-plans" }
if (-not $PlansDir) { $PlansDir = Join-Path $env:USERPROFILE ".workflow-plans" }

if (-not (Test-Path (Join-Path $ProjectsDir ".git"))) {
    Write-Error "Session sync not initialized. Run install.ps1 or install\win\session-sync-init.ps1 first."
    return
}

function Show-SessionToast([string]$Message) {
    # WinRT type loading requires Windows PowerShell 5.1 — invoke via powershell.exe so this works from both pwsh 7+ and PS 5.1.
    # Tag+Group: consecutive pushes replace the previous toast in Action Center instead of accumulating.
    $escaped = $Message -replace "'", "''"
    $script = @"
[void][Windows.UI.Notifications.ToastNotificationManager, Windows.UI.Notifications, ContentType = WindowsRuntime]
[void][Windows.Data.Xml.Dom.XmlDocument, Windows.Data.Xml.Dom.XmlDocument, ContentType = WindowsRuntime]
`$xml = [Windows.UI.Notifications.ToastNotificationManager]::GetTemplateContent([Windows.UI.Notifications.ToastTemplateType]::ToastText02)
`$text = `$xml.GetElementsByTagName('text')
[void]`$text.Item(0).AppendChild(`$xml.CreateTextNode('session-sync'))
[void]`$text.Item(1).AppendChild(`$xml.CreateTextNode('$escaped'))
`$toast = [Windows.UI.Notifications.ToastNotification]::new(`$xml)
`$toast.Tag = 'session-sync'
`$toast.Group = 'session-sync'
[Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier('PowerShell').Show(`$toast)
"@
    powershell.exe -NoProfile -Command $script 2>&1 | Out-Null
}

switch ($Action) {
    "push" {
        # Ensure .gitattributes is up to date (idempotent migration)
        $gitattributesPath = Join-Path $ProjectsDir ".gitattributes"
        $canonicalContent = "# All files under this repo are machine-generated by Claude Code`n* text eol=lf`n*.jsonl merge=union`n"
        $existing = if (Test-Path $gitattributesPath) { Get-Content $gitattributesPath -Raw } else { "" }
        if ($existing -ne $canonicalContent) {
            [System.IO.File]::WriteAllText($gitattributesPath, $canonicalContent)
            $ErrorActionPreference = "Continue"
            git -C $ProjectsDir add .gitattributes 2>&1 | Out-Null
            git -C $ProjectsDir commit -q -m "chore: union merge for jsonl to avoid rebase conflicts" 2>&1 | Out-Null
            $ErrorActionPreference = "Stop"
        }

        # Warn if Claude Code is running (JSONL may not be flushed)
        $claudeProcs = Get-Process -Name "claude" -ErrorAction SilentlyContinue
        if ($claudeProcs) {
            Write-Warning "Claude Code is running. Close all sessions before push to ensure latest data is saved."
        }

        # Copy history.jsonl into sync area
        Copy-Item (Join-Path $ClaudeDir "history.jsonl") (Join-Path $ProjectsDir ".history.jsonl") -ErrorAction SilentlyContinue
        # Copy plans into sync area
        $plansSource = $PlansDir
        $plansDest = Join-Path $ProjectsDir "plans"
        if (Test-Path $plansSource) {
            if (-not (Test-Path $plansDest)) { New-Item -ItemType Directory -Path $plansDest -Force | Out-Null }
            Get-ChildItem -Path $plansSource -File | Where-Object { $_.Extension -eq '.md' } | Copy-Item -Destination $plansDest -Force
        }
        $ErrorActionPreference = "Continue"
        git -C $ProjectsDir add . 2>&1 | Out-Null
        $ErrorActionPreference = "Stop"
        $status = git -C $ProjectsDir status --porcelain
        if (-not $status) {
            Write-Host "No changes to push."
            return
        }

        $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm"
        git -C $ProjectsDir commit -q -m "sync: $env:COMPUTERNAME $timestamp"
        # Retry loop: handles simultaneous push race (e.g. Windows + macOS committing at the same time)
        $maxRetries = 3
        $pushExitCode = 1
        $pushFailReason = ""
        for ($retry = 0; $retry -lt $maxRetries; $retry++) {
            $ErrorActionPreference = "Continue"
            # Commit any new session files written since the last commit
            git -C $ProjectsDir add . 2>&1 | Out-Null
            if (git -C $ProjectsDir status --porcelain 2>&1) {
                $ts2 = Get-Date -Format "yyyy-MM-dd HH:mm"
                git -C $ProjectsDir commit -q -m "sync: $env:COMPUTERNAME $ts2" 2>&1 | Out-Null
            }
            # Abort any rebase left stuck by a previous failed attempt
            git -C $ProjectsDir rebase --abort 2>&1 | Out-Null
            # Same bug class as the #1757 pull fix: an unchecked pull lets a failed
            # or half-finished rebase be pushed over the remote. A remote that has
            # no `main` yet is the one legitimate failure — the first publish —
            # so the abort is conditioned on the branch actually existing.
            git -C $ProjectsDir pull --rebase --autostash -X theirs origin main 2>&1 | Out-Null
            $pullExitCode = $LASTEXITCODE
            if ($pullExitCode -ne 0) {
                $remoteHeads = git -C $ProjectsDir ls-remote --heads origin main 2>&1 | Out-String
                if ($LASTEXITCODE -eq 0 -and $remoteHeads -match 'refs/heads/main') {
                    $pushExitCode = $pullExitCode
                    $pushFailReason = "git pull --rebase failed with exit code $pullExitCode; push aborted"
                    $ErrorActionPreference = "Stop"
                    break
                }
            }
            git -C $ProjectsDir push -u origin main 2>&1 | Out-Null
            $pushExitCode = $LASTEXITCODE
            $ErrorActionPreference = "Stop"
            if ($pushExitCode -eq 0) { break }
        }
        if ($pushExitCode -eq 0) {
            if ($Quiet) { Show-SessionToast "push complete" }
            else { Write-Host "Pushed session data." -ForegroundColor Green }
        } else {
            if (-not $pushFailReason) { $pushFailReason = "git push failed with exit code $pushExitCode" }
            if ($Quiet) { Show-SessionToast "push failed (exit code $pushExitCode)" }
            else { throw $pushFailReason }
        }
    }
    "pull" {
        # git writes progress to stderr even on success, so a Stop preference would
        # abort a healthy pull (#1757). Judge the pull by its exit code only, and
        # do it before any merge work: a failed pull must never reach the merges.
        $pullExitCode = 1
        $_prevEap = $ErrorActionPreference
        try {
            $ErrorActionPreference = "Continue"
            git -C $ProjectsDir pull --rebase 2>&1 | Where-Object { $_ -notmatch '^\s*(create|delete) mode ' }
            $pullExitCode = $LASTEXITCODE
        } finally {
            $ErrorActionPreference = $_prevEap
        }
        if ($pullExitCode -ne 0) {
            throw "git pull failed with exit code $pullExitCode"
        }
        # Merge remote history with local (dedup, preserve order)
        $syncHistory = Join-Path $ProjectsDir ".history.jsonl"
        $localHistory = Join-Path $ClaudeDir "history.jsonl"
        if (Test-Path $syncHistory) {
            $remote = @(Get-Content $syncHistory -ErrorAction SilentlyContinue)
            $local = @(Get-Content $localHistory -ErrorAction SilentlyContinue)
            $seen = [ordered]@{}
            foreach ($line in $remote + $local) { if ($line -and -not $seen.Contains($line)) { $seen[$line] = $true } }
            $seen.Keys | Set-Content $localHistory
        }
        # Merge plans from remote into local
        $syncPlans = Join-Path $ProjectsDir "plans"
        $localPlans = $PlansDir
        if (Test-Path $syncPlans) {
            if (-not (Test-Path $localPlans)) { New-Item -ItemType Directory -Path $localPlans -Force | Out-Null }
            Get-ChildItem -Path $syncPlans -File | Where-Object { $_.Extension -eq '.md' -and (Test-Path $_.FullName) } | Copy-Item -Destination $localPlans -Force
        }
        Write-Host "Pulled session data." -ForegroundColor Green
    }
    "status" {
        git -C $ProjectsDir status
    }
    "reset" {
        # Same bug class as the #1757 pull fix: git writes progress to stderr even
        # on success, so the fetch is judged by its exit code only — and judged at
        # all, because `reset --hard` is destructive and a silent fetch failure
        # would reset onto a stale origin/main.
        $fetchExitCode = 1
        $_prevEap = $ErrorActionPreference
        try {
            $ErrorActionPreference = "Continue"
            git -C $ProjectsDir fetch origin main 2>&1 | Out-Null
            $fetchExitCode = $LASTEXITCODE
        } finally {
            $ErrorActionPreference = $_prevEap
        }
        if ($fetchExitCode -ne 0) {
            throw "git fetch failed with exit code $fetchExitCode"
        }
        git -C $ProjectsDir reset --hard origin/main
        # Restore mtime from JSONL timestamps (git doesn't preserve mtime)
        Get-ChildItem -Path $ProjectsDir -Recurse -Filter "*.jsonl" | Where-Object { $_.Name -ne ".history.jsonl" } | ForEach-Object {
            $tsLine = Get-Content $_.FullName -ErrorAction SilentlyContinue |
                Where-Object { $_ -match '"timestamp":"([^"]+)"' } | Select-Object -Last 1
            if ($tsLine -match '"timestamp":"([^"]+)"') {
                try { $_.LastWriteTime = [datetime]::Parse($Matches[1]).ToLocalTime() } catch {}
            }
        }
        # Merge remote history with local (dedup, preserve order)
        $syncHistory = Join-Path $ProjectsDir ".history.jsonl"
        $localHistory = Join-Path $ClaudeDir "history.jsonl"
        if (Test-Path $syncHistory) {
            $remote = @(Get-Content $syncHistory -ErrorAction SilentlyContinue)
            $local = @(Get-Content $localHistory -ErrorAction SilentlyContinue)
            $seen = [ordered]@{}
            foreach ($line in $remote + $local) { if ($line -and -not $seen.Contains($line)) { $seen[$line] = $true } }
            $seen.Keys | Set-Content $localHistory
        }
        # Merge plans from remote into local
        $syncPlans = Join-Path $ProjectsDir "plans"
        $localPlans = $PlansDir
        if (Test-Path $syncPlans) {
            if (-not (Test-Path $localPlans)) { New-Item -ItemType Directory -Path $localPlans -Force | Out-Null }
            Get-ChildItem -Path $syncPlans -File | Where-Object { $_.Extension -eq '.md' -and (Test-Path $_.FullName) } | Copy-Item -Destination $localPlans -Force
        }
        Write-Host "Reset to remote state." -ForegroundColor Green
    }
}
