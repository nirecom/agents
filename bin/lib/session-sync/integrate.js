"use strict";
// Integration (#2658): build M from W, L = main and R = origin/main with plumbing only, publish it
// by fast-forward push (push) or keep it local (pull / reset), then write W. Never rebase or merge.

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const G = require("./git");
const { classify } = require("./classify");
const { mergeHistory } = require("./history");
const { applyManagedBlock } = require("./exclude");
const { applyOps, writeAtomic, setMtime, statSig } = require("./apply");
const { heal, resolveUnmerged } = require("./selfheal");
const { newStats } = require("./state");
const plans = require("./plans");
const lock = require("./lock");

const GITATTRIBUTES = "# All files under this repo are machine-generated by Claude Code\n* text eol=lf\n*.jsonl merge=union\n";
const MAX_ATTEMPTS = 3;

const readOrNull = (file) => { try { return fs.readFileSync(file, "utf8"); } catch (_) { return null; } };

function writeIfChanged(file, text) {
  if (readOrNull(file) === text) return;
  writeAtomic(file, text);
}

// workingChanges(dir, L, lMap) -> Map rel -> {kind: "del", sig: null} | {kind: "mod", blob, mode, sig}
// sig is taken before hashing, so a write that lands after it is seen by applyOps.
function workingChanges(dir, L, lMap) {
  G.setIndex(dir, L);
  const raw = G.gitOut(dir, ["status", "--porcelain=v2", "-z", "--untracked-files=all", "--no-renames"]);
  if (raw === null) throw new Error("git status failed");
  const w = new Map();
  const changed = [];
  for (const rec of raw.split("\0")) {
    const parts = rec.split(" ");
    if (parts[0] === "1" && parts.length > 8) {
      const rel = parts.slice(8).join(" ");
      if (parts[1][1] === "D") w.set(rel, { kind: "del", sig: null });
      else if (parts[1][1] !== "." && !/^1[26]0000$/.test(parts[5])) changed.push({ rel, mode: parts[5] });
    } else if (parts[0] === "u" && parts.length > 10) {
      changed.push({ rel: parts.slice(10).join(" "), mode: "100644" });
    } else if (parts[0] === "?") {
      const rel = rec.slice(2);
      const st = fs.lstatSync(path.join(dir, rel), { throwIfNoEntry: false });
      if (st && st.isFile()) changed.push({ rel, mode: "100644" });
    }
  }
  const safe = changed.filter((e) => !/[\r\n]/.test(e.rel));
  const sigs = safe.map((e) => statSig(path.join(dir, ...e.rel.split("/"))));
  const shas = G.hashPaths(dir, safe.map((e) => e.rel));
  safe.forEach((e, i) => {
    const l = lMap.get(e.rel);
    if (!(l && l.blob === shas[i])) w.set(e.rel, { kind: "mod", blob: shas[i], mode: e.mode === "100755" ? e.mode : "100644", sig: sigs[i] });
  });
  return w;
}

// history(ctx, out, claudeDir) — ~/.claude/history.jsonl, W's .history.jsonl and R's are unioned.
function history(c, out, claudeDir) {
  const file = path.join(claudeDir, "history.jsonl");
  const localText = readOrNull(file);
  const wText = readOrNull(c.abs(".history.jsonl"));
  const rSha = c.R ? G.gitOut(c.dir, ["rev-parse", "--verify", "-q", `${c.R}:.history.jsonl`]) : null;
  const rText = rSha ? c.blobText(rSha) : null;
  if (localText === null && wText === null && rText === null) return null;
  const merged = mergeHistory(localText, wText).text;
  const final = rText !== null && !mergeHistory(rText, merged).changed ? rText : mergeHistory(merged, rText).text;
  out.delta.set(".history.jsonl", { mode: "100644", blob: c.blobFor(final, rSha ? [rSha] : []) });
  if (final !== wText) out.ops.push({ rel: ".history.jsonl", kind: "text", text: final });
  return { file, localText, final };
}

function writeHistoryLocal(h) {
  if (!h || h.final === h.localText) return false;
  const now = readOrNull(h.file);
  const text = now === h.localText ? h.final : mergeHistory(now, h.final).text;
  if (text === now) return false;
  writeAtomic(h.file, text);
  return true;
}

// build(...) -> {newMain, out, hist, ctx}: M as a tree, then the commit main should point at.
function build(o, L, R, lMap, w, stats) {
  const dir = o.dir;
  const empty = G.emptyTree(dir);
  const base = { mode: o.action === "reset" ? "reset" : "sync", dir, host: os.hostname().split(".")[0], now: new Date(), R, lMap, w, stats };
  if (base.mode === "reset") {
    base.rMap = G.lsTree(dir, R);
  } else {
    const B = G.mergeBase(dir, L, R) || empty;
    base.rDiff = R ? G.diffTree(dir, B, R) : new Map();
    base.lDiff = L ? G.diffTree(dir, B, L) : new Map();
  }
  const { out, ctx } = classify(base);
  out.delta.set(".gitattributes", { mode: "100644", blob: G.hashText(dir, GITATTRIBUTES) });
  if (base.rDiff && base.rDiff.has(".gitignore")) {
    const g = base.rDiff.get(".gitignore");
    out.delta.set(".gitignore", g.newBlob ? { mode: g.mode, blob: g.newBlob } : null);
  }
  const hist = history(ctx, out, o.claudeDir);
  const mTree = G.writeTree(dir, base.mode === "reset" ? R : L, out.delta);
  let newMain;
  if (R && mTree === G.treeOf(dir, R)) newMain = R;
  else if (L && mTree === G.treeOf(dir, L) && (!R || G.isAncestor(dir, R, L))) newMain = L;
  else if (!L && !R && mTree === empty) newMain = null;
  else newMain = G.commitTree(dir, mTree, R || L, `sync: ${os.hostname().split(".")[0]} ${new Date().toISOString()}`);
  return { newMain, out, hist, ctx };
}

function fetchOnce(dir) {
  const r = G.fetch(dir);
  if (r.status === 0) return null;
  if (/couldn't find remote ref|could not find remote ref/i.test(r.stderr)) {
    G.git(dir, ["update-ref", "-d", G.ORIGIN]);
    return null;
  }
  return { result: G.failureKind(r), error: (r.stderr || "git fetch failed").trim() };
}

// finish(...) — main moves by compare-and-swap, then the index and W follow it.
function finish(o, L, lMap, b, stats) {
  const dir = o.dir;
  const cur = G.revParse(dir, G.MAIN);
  if (b.newMain && b.newMain !== cur && !G.casUpdate(dir, G.MAIN, b.newMain, cur)) throw new Error("main moved during sync");
  G.setIndex(dir, b.newMain);
  if (G.revParse(dir, G.ORIGIN)) G.ensureUpstream(dir);
  let written = applyOps(dir, b.out.ops, (sha) => G.catBlob(dir, sha), stats);
  if (o.action === "reset") {
    const rels = new Set([...b.ctx.rMap.keys(), ...b.ctx.w.keys(), ...lMap.keys()]);
    for (const rel of rels) {
      if (rel.endsWith(".jsonl") && rel !== ".history.jsonl" && fs.existsSync(b.ctx.abs(rel))) setMtime(b.ctx.abs(rel), rel, stats);
    }
  }
  if (writeHistoryLocal(b.hist)) written += 1;
  // push too: a plan that arrived through this integration must reach plansDir, or the next push's
  // toProjects would copy the stale plansDir copy back over the newer one.
  written += plans.fromProjects(o.plansDir, dir, lMap);
  return { mainChanged: (b.newMain || null) !== (cur || null), written };
}

async function integrate(o, stats) {
  const dir = o.dir;
  const healed = heal(dir);
  resolveUnmerged(dir, healed.unmerged, G.revParse(dir, G.ORIGIN) || healed.main, stats);
  writeIfChanged(path.join(dir, ".gitignore"), applyManagedBlock(readOrNull(path.join(dir, ".gitignore"))));
  writeIfChanged(path.join(dir, ".gitattributes"), GITATTRIBUTES);
  if (o.action === "push") plans.toProjects(o.plansDir, dir);
  const L = healed.main;
  const lMap = G.lsTree(dir, L);
  const w = workingChanges(dir, L, lMap);
  for (let attempt = 1; ; attempt += 1) {
    if (!o.skipFetch || attempt > 1 || o.action === "reset") {
      const bad = fetchOnce(dir);
      if (bad) return Object.assign(bad, { attempts: attempt });
    }
    const R = G.revParse(dir, G.ORIGIN);
    if (o.action === "reset" && !R) return { result: "failed", error: "the remote has no main branch to reset to", attempts: attempt };
    const b = build(o, L, R, lMap, w, stats);
    let pushed = false;
    if (o.action === "push" && b.newMain && b.newMain !== R) {
      const p = G.push(dir, b.newMain);
      if (p.status !== 0) {
        if (G.isNonFastForward(p) && attempt < MAX_ATTEMPTS) continue;
        return { result: G.failureKind(p) === "offline" ? "offline" : "failed", error: (p.stderr || "git push failed").trim(), attempts: attempt };
      }
      G.git(dir, ["update-ref", G.ORIGIN, b.newMain]);
      pushed = true;
    }
    const f = finish(o, L, lMap, b, stats);
    const changed = o.action === "push" ? pushed : (f.mainChanged || f.written > 0 || o.action === "reset");
    return { result: changed ? "ok" : "no-change", attempts: attempt };
  }
}

// run(o) -> {result, error, attempts, stats}; o: {action, dir, claudeDir, plansDir, skipFetch, waitMs}
async function run(o) {
  const stats = newStats();
  const held = await lock.acquire(path.join(o.dir, ".git"), { waitMs: o.waitMs === undefined ? 30000 : o.waitMs });
  if (!held) return { result: "busy", error: "another session-sync run holds the lock", attempts: 0, stats };
  try {
    return Object.assign(await integrate(o, stats), { stats });
  } catch (e) {
    return { result: "failed", error: String(e && e.message ? e.message : e), attempts: 1, stats };
  } finally {
    await held.release();
  }
}

module.exports = { GITATTRIBUTES, run, workingChanges };
