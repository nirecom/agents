"use strict";
// Fixture helpers for tests/bin/feature-2658-session-sync-engine.js (#2658). Holds no case markers.
// Two machines are two fixture homes, each with its own ~/.claude/projects clone of one bare
// remote; git runs under an isolated GIT_CONFIG_GLOBAL whose core.hooksPath is /dev/null.
const assert = require("node:assert");
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const REPO = path.join(__dirname, "..", "..", "..");
const ENGINE = path.join(REPO, "bin", "session-sync-engine");
const LIB = path.join(REPO, "bin", "lib", "session-sync");
const STATE_FILE = "agents-session-sync-state.json";

function makeFixtures(TMP) {
  let seq = 0;
  const gitConfig = path.join(TMP, "gitconfig");
  const emptyIgnore = path.join(TMP, "empty-ignore");
  fs.writeFileSync(emptyIgnore, "");
  fs.writeFileSync(gitConfig, [
    "[user]", "  name = f2658", "  email = f2658@example.invalid",
    "[init]", "  defaultBranch = main", "[commit]", "  gpgSign = false",
    "[core]", "  hooksPath = /dev/null", "  autocrlf = false",
    `  excludesFile = ${emptyIgnore.replace(/\\/g, "/")}`,
    "[advice]", "  detachedHead = false",
    "[maintenance]", "  auto = false", "[gc]", "  auto = 0", "",
  ].join("\n"));

  function gitEnv(extra) {
    const env = Object.assign({}, process.env, {
      GIT_CONFIG_GLOBAL: gitConfig, GIT_CONFIG_NOSYSTEM: "1", GIT_TERMINAL_PROMPT: "0",
      XDG_CONFIG_HOME: TMP,
    }, extra || {});
    delete env.CLAUDE_CODE_SESSION_ID;
    return env;
  }

  function git(cwd, args, { allowFail = false } = {}) {
    const done = spawnSync("git", ["-C", cwd, ...args], { encoding: "utf8", env: gitEnv() });
    if (!allowFail) assert.strictEqual(done.status, 0, `git ${args.join(" ")}: ${done.stderr}`);
    return allowFail ? done : done.stdout.trim();
  }

  function write(file, text) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }

  // world({ seed }) -> { remote, seed, a, b } where a / b are machines:
  //   { home, claude, projects, plans }. seed maps repo paths to contents of the first commit.
  function world({ seed = {} } = {}) {
    seq += 1;
    const root = path.join(TMP, `w${seq}`);
    const remote = path.join(root, "remote.git");
    const seedDir = path.join(root, "seed");
    fs.mkdirSync(root, { recursive: true });
    git(root, ["init", "-q", "--bare", remote]);
    git(root, ["clone", "-q", remote, seedDir]);
    const files = Object.assign({
      ".gitattributes": "# All files under this repo are machine-generated by Claude Code\n* text eol=lf\n*.jsonl merge=union\n",
      "seed-project/seed.jsonl": jline("seed-0") + "\n",
    }, seed);
    for (const [rel, text] of Object.entries(files)) write(path.join(seedDir, rel), text);
    git(seedDir, ["add", "-A"]);
    git(seedDir, ["commit", "-q", "-m", "seed"]);
    git(seedDir, ["push", "-q", "-u", "origin", "main"]);
    const machine = (name) => {
      const home = path.join(root, name);
      const claude = path.join(home, ".claude");
      const projects = path.join(claude, "projects");
      const plans = path.join(home, "plans");
      fs.mkdirSync(plans, { recursive: true });
      git(root, ["clone", "-q", remote, projects]);
      return { name, home, claude, projects, plans };
    };
    return { root, remote, seed: seedDir, a: machine("a"), b: machine("b") };
  }

  // engine(m, action, args, opts) — runs the engine CLI as machine m.
  function engine(m, action, args = [], { env = {}, timeout = 90000 } = {}) {
    const argv = [ENGINE, ...(action ? [action] : []), "--claude-dir", m.claude, "--plans-dir", m.plans, ...args];
    const done = spawnSync(process.execPath, argv, {
      encoding: "utf8", timeout, cwd: m.home,
      env: gitEnv(Object.assign({ HOME: m.home, USERPROFILE: m.home }, env)),
    });
    return { code: done.status, stdout: done.stdout || "", stderr: done.stderr || "", error: done.error };
  }

  function show(dir, ref, rel) {
    const done = git(dir, ["show", `${ref}:${rel}`], { allowFail: true });
    return done.status === 0 ? done.stdout : null;
  }

  function readState(m) {
    const file = path.join(m.projects, ".git", STATE_FILE);
    return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : null;
  }

  function lib(name) {
    return require(path.join(LIB, `${name}.js`));
  }

  return { REPO, ENGINE, LIB, TMP, git, gitEnv, write, world, engine, show, readState, lib };
}

// jline(uuid, extra) — one transcript entry line (no trailing newline).
function jline(uuid, extra = {}) {
  return JSON.stringify(Object.assign({ uuid, type: "user", timestamp: "2026-01-02T03:04:05.000Z" }, extra));
}

function pidAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return e.code === "EPERM";
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

module.exports = { makeFixtures, jline, pidAlive, sleep };
