// Two-clone rule parts of tests/bin/feature-2658-session-sync-engine.js (#2658): exclusion, jsonl
// union across machines, history merge, non-jsonl conflict siblings, mtime apply, self-heal.
// Holds no case markers; every case drives the real engine CLI.
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");
const { test } = require("node:test");
const { jline, sleep } = require("./fixtures");

const okRun = (r, what) => assert.strictEqual(r.code, 0, `${what}: exit ${r.code}\nstdout: ${r.stdout}\nstderr: ${r.stderr}`);
const read = (...p) => fs.readFileSync(path.join(...p), "utf8");
const siblingsOf = (dir, stem) => fs.readdirSync(dir).filter((n) => n.startsWith(`${stem}.sync-conflict-`));

function excluded(F) {
  test("tracked excluded files leave the index and the remote but stay on disk", () => {
    const w = F.world({ seed: { "workflow/state.json": "{}\n", "plans/x.json": "{}\n", "plans/keep.md": "# k\n", "p1/a.tmp": "t\n" } });
    const r = F.engine(w.a, "push");
    okRun(r, "A push");
    for (const rel of ["workflow/state.json", "plans/x.json", "p1/a.tmp"]) {
      assert.strictEqual(F.git(w.a.projects, ["ls-files", "--", rel]), "", `${rel} must leave the index`);
      assert.ok(fs.existsSync(path.join(w.a.projects, rel)), `${rel} must stay on disk`);
      assert.strictEqual(F.show(w.remote, "main", rel), null, `${rel} must leave the remote tree`);
    }
    assert.ok(F.show(w.remote, "main", "plans/keep.md") !== null, "plans/*.md stays synced");
    const gi = read(w.a.projects, ".gitignore");
    assert.ok(gi.includes("# BEGIN agents session-sync (managed)") && gi.includes("/workflow/"), gi);
    okRun(F.engine(w.b, "pull"), "B pull");
    assert.ok(fs.existsSync(path.join(w.b.projects, "workflow", "state.json")), "another machine keeps its excluded file");
  });
  test("integration writes the canonical .gitattributes", () => {
    const w = F.world({ seed: { ".gitattributes": "*.jsonl merge=union\n" } });
    okRun(F.engine(w.a, "pull"), "A pull");
    assert.strictEqual(read(w.a.projects, ".gitattributes"),
      "# All files under this repo are machine-generated by Claude Code\n* text eol=lf\n*.jsonl merge=union\n");
  });
}

function jsonlBoth(F) {
  const h = (ts) => JSON.stringify({ display: `d${ts}`, timestamp: ts, project: "p" });
  test("a transcript appended on both machines converges to the union on both", () => {
    const base = jline("base") + "\n";
    const w = F.world({ seed: { "p1/shared.jsonl": base } });
    fs.appendFileSync(path.join(w.a.projects, "p1", "shared.jsonl"), jline("fromA") + "\n");
    fs.appendFileSync(path.join(w.b.projects, "p1", "shared.jsonl"), jline("fromB") + "\n");
    okRun(F.engine(w.a, "push"), "A push");
    okRun(F.engine(w.b, "push"), "B push");
    const remote = F.show(w.remote, "main", "p1/shared.jsonl");
    for (const id of ["base", "fromA", "fromB"]) assert.ok(remote.includes(`"uuid":"${id}"`), `remote lacks ${id}: ${remote}`);
    assert.strictEqual(read(w.b.projects, "p1", "shared.jsonl"), base + jline("fromB") + "\n" + jline("fromA") + "\n");
    okRun(F.engine(w.a, "pull"), "A pull");
    const a = read(w.a.projects, "p1", "shared.jsonl");
    assert.strictEqual(a, remote, "A adopts the remote line order after the pull");
    assert.ok(!/^(<{7}|={7}|>{7})/m.test(a + remote), "no conflict markers");
    const again = F.engine(w.a, "push");
    okRun(again, "A push after converging");
    assert.strictEqual(again.stdout.trim(), "No changes to push.", "the union must converge, not ping-pong");
  });
  test("history.jsonl from two machines is unioned and time-sorted on both", () => {
    const w = F.world();
    F.write(path.join(w.a.claude, "history.jsonl"), [h(10), h(30)].join("\n") + "\n");
    F.write(path.join(w.b.claude, "history.jsonl"), [h(20)].join("\n") + "\n");
    okRun(F.engine(w.a, "push"), "A push");
    okRun(F.engine(w.b, "push"), "B push");
    okRun(F.engine(w.a, "pull"), "A pull");
    const want = [h(10), h(20), h(30)].join("\n") + "\n";
    assert.strictEqual(read(w.a.claude, "history.jsonl"), want);
    assert.strictEqual(read(w.b.claude, "history.jsonl"), want);
    assert.strictEqual(F.show(w.remote, "main", ".history.jsonl"), want);
  });
  test("reset unions another machine's history.jsonl time-sorted, is idempotent, and keeps the union local", () => {
    const w = F.world();
    const pushedByA = [h(10), h(30)].join("\n") + "\n";
    F.write(path.join(w.a.claude, "history.jsonl"), pushedByA);
    F.write(path.join(w.b.claude, "history.jsonl"), [h(20)].join("\n") + "\n");
    okRun(F.engine(w.a, "push"), "A push");
    const tip = F.git(w.remote, ["rev-parse", "main"]);
    const want = [h(10), h(20), h(30)].join("\n") + "\n";
    const assertUnionKeptLocal = () => {
      assert.strictEqual(read(w.b.claude, "history.jsonl"), want);
      assert.strictEqual(read(w.b.projects, ".history.jsonl"), want);
      assert.strictEqual(F.show(w.b.projects, "main", ".history.jsonl"), want);
      assert.strictEqual(F.git(w.remote, ["rev-parse", "main"]), tip, "reset does not push");
      assert.strictEqual(F.show(w.remote, "main", ".history.jsonl"), pushedByA);
    };
    okRun(F.engine(w.b, "reset"), "B reset");
    assertUnionKeptLocal();
    const mainAfterFirst = F.git(w.b.projects, ["rev-parse", "main"]);
    okRun(F.engine(w.b, "reset"), "B second reset");
    assertUnionKeptLocal();
    assert.strictEqual(F.git(w.b.projects, ["rev-parse", "main"]), mainAfterFirst, "a second reset leaves main alone");
  });
}

function conflicts(F) {
  test("a non-jsonl file changed on both machines within the skew window keeps both versions", () => {
    const w = F.world({ seed: { "p1/note.md": "base\n" } });
    F.write(path.join(w.a.projects, "p1", "note.md"), "from A\n");
    F.write(path.join(w.b.projects, "p1", "note.md"), "from B\n");
    okRun(F.engine(w.a, "push"), "A push");
    okRun(F.engine(w.b, "push"), "B push");
    assert.strictEqual(read(w.b.projects, "p1", "note.md"), "from A\n", "the remote version stays at the path");
    const sib = fs.readdirSync(path.join(w.b.projects, "p1")).filter((n) => /^note\.sync-conflict-.+-\d{8}T\d{6}Z(-\d+)?\.md$/.test(n));
    assert.strictEqual(sib.length, 1, `siblings: ${fs.readdirSync(path.join(w.b.projects, "p1"))}`);
    assert.strictEqual(read(w.b.projects, "p1", sib[0]), "from B\n");
    assert.ok(F.show(w.remote, "main", `p1/${sib[0]}`) !== null, "the sibling is synced too");
    const st = F.readState(w.b);
    assert.ok(st.conflicts.some((c) => c.path === "p1/note.md" && c.copy === `p1/${sib[0]}`), JSON.stringify(st.conflicts));
  });
  test("a local edit far newer than the remote change wins without a sibling", () => {
    const w = F.world({ seed: { "p1/note.md": "base\n" } });
    F.write(path.join(w.a.projects, "p1", "note.md"), "from A\n");
    okRun(F.engine(w.a, "push"), "A push");
    const file = path.join(w.b.projects, "p1", "note.md");
    F.write(file, "from B\n");
    const future = new Date(Date.now() + 10 * 60 * 1000);
    fs.utimesSync(file, future, future);
    okRun(F.engine(w.b, "push"), "B push");
    assert.strictEqual(F.show(w.remote, "main", "p1/note.md"), "from B\n");
    assert.deepStrictEqual(siblingsOf(path.join(w.b.projects, "p1"), "note"), []);
  });
  // T_W < T_R - S: the remote version is adopted at the path, as the conflict rule specifies.
  test("a local edit far older than the remote change loses to the remote and is never pushed", () => {
    const w = F.world({ seed: { "p1/note.md": "base\n" } });
    F.write(path.join(w.a.projects, "p1", "note.md"), "from A (new)\n");
    okRun(F.engine(w.a, "push"), "A push");
    const tipA = F.git(w.remote, ["rev-parse", "main"]);
    const file = path.join(w.b.projects, "p1", "note.md");
    F.write(file, "from B (old)\n");
    const past = new Date(Date.now() - 10 * 60 * 1000);
    fs.utimesSync(file, past, past);
    okRun(F.engine(w.b, "push"), "B push");
    assert.strictEqual(F.show(w.remote, "main", "p1/note.md"), "from A (new)\n", "the newer remote version must survive");
    assert.strictEqual(F.git(w.remote, ["merge-base", "--is-ancestor", tipA, "main"], { allowFail: true }).status, 0, "no force push");
    assert.strictEqual(read(w.b.projects, "p1", "note.md"), "from A (new)\n", "B's working tree takes the remote version");
    assert.deepStrictEqual(siblingsOf(path.join(w.b.projects, "p1"), "note"), [], "outside the skew window no sibling is made");
  });
}

function mtimeApply(F) {
  test("pulled transcripts get their timestamp as mtime; option-like values are rejected silently and counted", () => {
    const w = F.world();
    F.write(path.join(w.a.projects, "p1", "good.jsonl"), jline("g", { timestamp: "2024-05-06T07:08:09.000Z" }) + "\n");
    F.write(path.join(w.a.projects, "p1", "evil.jsonl"), jline("e", { timestamp: "--date=@0" }) + "\n");
    okRun(F.engine(w.a, "push"), "A push");
    const t0 = Date.now();
    const r = F.engine(w.b, "pull");
    okRun(r, "B pull");
    assert.strictEqual(r.stderr, "", "the apply path never writes to stderr");
    const good = fs.statSync(path.join(w.b.projects, "p1", "good.jsonl")).mtimeMs;
    assert.ok(Math.abs(good - Date.parse("2024-05-06T07:08:09.000Z")) < 2000, `good mtime ${new Date(good).toISOString()}`);
    const evil = fs.statSync(path.join(w.b.projects, "p1", "evil.jsonl")).mtimeMs;
    assert.ok(evil > t0 - 60000, `evil mtime was changed to ${new Date(evil).toISOString()}`);
    const st = F.readState(w.b);
    const rejected = typeof st.mtimeRejected === "number" ? st.mtimeRejected : st.mtimeRejected.count;
    assert.ok(rejected >= 1, JSON.stringify(st.mtimeRejected));
  });
}

// stuckMidRebase(F, w) — leaves machine A as #2291 does: HEAD detached, rebase-merge and merge
// state present, plus an unpushed local transcript; B has pushed a change A has not seen.
function stuckMidRebase(F, w) {
  const gd = path.join(w.a.projects, ".git");
  F.write(path.join(w.b.projects, "p2", "fromB.jsonl"), jline("b1") + "\n");
  okRun(F.engine(w.b, "push"), "B push");
  F.git(w.a.projects, ["checkout", "-q", "--detach"]);
  fs.mkdirSync(path.join(gd, "rebase-merge"), { recursive: true });
  fs.writeFileSync(path.join(gd, "rebase-merge", "head-name"), "refs/heads/main\n");
  fs.writeFileSync(path.join(gd, "MERGE_HEAD"), F.git(w.a.projects, ["rev-parse", "HEAD"]) + "\n");
  fs.writeFileSync(path.join(gd, "MERGE_MSG"), "stuck\n");
  F.write(path.join(w.a.projects, "p1", "local.jsonl"), jline("l1") + "\n");
  return gd;
}

function assertHealed(F, w, gd) {
  for (const n of ["rebase-merge", "rebase-apply", "MERGE_HEAD", "MERGE_MSG"]) {
    assert.ok(!fs.existsSync(path.join(gd, n)), `${n} must be removed`);
  }
  assert.strictEqual(F.git(w.a.projects, ["symbolic-ref", "HEAD"]), "refs/heads/main");
  assert.strictEqual(read(w.a.projects, "p1", "local.jsonl"), jline("l1") + "\n", "the working tree is kept");
  assert.strictEqual(read(w.a.projects, "p2", "fromB.jsonl"), jline("b1") + "\n", "the sync completes");
}

// realRebaseConflict(F, w) — A commits its own edits, B pushes conflicting ones, and A runs a real
// `git rebase` that stops with unmerged paths and conflict markers in both a jsonl and a non-jsonl.
function realRebaseConflict(F, w) {
  const A = w.a.projects;
  fs.appendFileSync(path.join(w.b.projects, "p1", "c.jsonl"), jline("fromB") + "\n");
  F.write(path.join(w.b.projects, "p1", "note.md"), "from B\n");
  okRun(F.engine(w.b, "push"), "B push");
  fs.appendFileSync(path.join(A, "p1", "c.jsonl"), jline("fromA") + "\n");
  F.write(path.join(A, "p1", "note.md"), "from A\n");
  F.git(A, ["commit", "-q", "-am", "A local"]);
  F.git(A, ["fetch", "-q", "origin"]);
  const attrs = path.join(A, ".git", "info", "attributes");
  F.write(attrs, "*.jsonl merge\n");
  assert.notStrictEqual(F.git(A, ["rebase", "origin/main"], { allowFail: true }).status, 0, "the rebase must stop");
  fs.rmSync(attrs);
  const unmerged = F.git(A, ["ls-files", "-u"]);
  for (const rel of ["p1/c.jsonl", "p1/note.md"]) {
    assert.ok(unmerged.includes(rel), `${rel} must be unmerged: ${unmerged}`);
    assert.ok(/^<{7}/m.test(read(A, rel)), `${rel} must hold conflict markers`);
  }
  assert.ok(fs.existsSync(path.join(A, ".git", "rebase-merge")), "rebase-merge must exist");
}

// assertBothSides — noteTexts are every p1/note* file's text, so a side may sit at the path or a sibling.
function assertBothSides(F, w, jsonlText, noteTexts) {
  for (const id of ["base", "fromA", "fromB"]) assert.ok(jsonlText.includes(`"uuid":"${id}"`), `jsonl lacks ${id}: ${jsonlText}`);
  assert.ok(!/^(<{7}|={7}|>{7})/m.test(jsonlText), `jsonl keeps conflict markers: ${jsonlText}`);
  const all = noteTexts.join("\n");
  for (const s of ["from A", "from B"]) assert.ok(all.includes(s), `non-jsonl lost "${s}": ${all}`);
  assert.strictEqual(F.git(w.a.projects, ["ls-files", "-u"]), "", "no unmerged path is left");
  assert.strictEqual(F.git(w.a.projects, ["symbolic-ref", "HEAD"]), "refs/heads/main");
  assert.ok(!fs.existsSync(path.join(w.a.projects, ".git", "rebase-merge")), "rebase-merge must be removed");
}

const localNotes = (m) => fs.readdirSync(path.join(m.projects, "p1")).filter((n) => n.startsWith("note"))
  .map((n) => read(m.projects, "p1", n));

function selfhealRealConflict(F) {
  const seed = { "p1/c.jsonl": jline("base") + "\n", "p1/note.md": "base\n" };
  test("a real rebase conflict heals in one push and keeps both sides of the jsonl and the non-jsonl", () => {
    const w = F.world({ seed });
    realRebaseConflict(F, w);
    okRun(F.engine(w.a, "push"), "A push from a real rebase conflict");
    assertBothSides(F, w, read(w.a.projects, "p1", "c.jsonl"), localNotes(w.a));
    const remoteNotes = F.git(w.remote, ["ls-tree", "--name-only", "main", "p1/"]).split("\n")
      .filter((n) => n.startsWith("p1/note")).map((n) => F.show(w.remote, "main", n));
    assertBothSides(F, w, F.show(w.remote, "main", "p1/c.jsonl"), remoteNotes);
    okRun(F.engine(w.b, "pull"), "B pull");
    const bNotes = localNotes(w.b).join("\n");
    for (const s of ["from A", "from B"]) assert.ok(bNotes.includes(s), `B lost "${s}": ${bNotes}`);
  });
  test("a real rebase conflict heals in one pull and keeps both sides of the jsonl and the non-jsonl", () => {
    const w = F.world({ seed });
    realRebaseConflict(F, w);
    okRun(F.engine(w.a, "pull"), "A pull from a real rebase conflict");
    assertBothSides(F, w, read(w.a.projects, "p1", "c.jsonl"), localNotes(w.a));
  });
}

function selfheal(F) {
  test("a clone stuck mid-rebase recovers in one push and keeps the working tree", () => {
    const w = F.world({ seed: { "p1/s.jsonl": jline("s0") + "\n" } });
    const gd = stuckMidRebase(F, w);
    const r = F.engine(w.a, "push");
    okRun(r, "A push from mid-rebase");
    assert.strictEqual(r.stdout.trim(), "Pushed session data.");
    assertHealed(F, w, gd);
    assert.ok(F.show(w.remote, "main", "p1/local.jsonl") !== null);
  });
  test("a clone stuck mid-rebase recovers in one pull and keeps the working tree", () => {
    const w = F.world({ seed: { "p1/s.jsonl": jline("s0") + "\n" } });
    const gd = stuckMidRebase(F, w);
    const r = F.engine(w.a, "pull");
    okRun(r, "A pull from mid-rebase");
    assertHealed(F, w, gd);
    assert.strictEqual(F.git(w.a.projects, ["merge-base", "--is-ancestor", "origin/main", "main"], { allowFail: true }).status, 0,
      "main is rebuilt on top of the fetched remote");
    assert.strictEqual(F.show(w.remote, "main", "p1/local.jsonl"), null, "a pull never publishes");
  });
  test("a clone stuck mid-rebase recovers through startup's background pull and keeps the working tree", async () => {
    const w = F.world({ seed: { "p1/s.jsonl": jline("s0") + "\n" } });
    const gd = stuckMidRebase(F, w);
    const r = F.engine(w.a, "startup", ["--quiet", "--deadline-ms", "3000"]);
    okRun(r, "A startup from mid-rebase");
    assert.deepStrictEqual([r.stdout, r.stderr], ["", ""], "startup stays silent");
    const healed = () => !fs.existsSync(path.join(gd, "rebase-merge")) && fs.existsSync(path.join(w.a.projects, "p2", "fromB.jsonl"));
    for (let i = 0; i < 100 && !healed(); i += 1) await sleep(200);
    for (let i = 0; i < 50 && fs.existsSync(path.join(gd, "agents-session-sync.lock")); i += 1) await sleep(200);
    assertHealed(F, w, gd);
  });
}

